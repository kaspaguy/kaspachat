import { existsSync, readFileSync } from 'node:fs';

// The bouncer's name policy: decides whether a Plus name may be sold on sign-up.
// The contract checks charset and length; this checks the reserved list and pattern rules.
export type Verdict = { allowed: true } | { allowed: false; disposition: 'auction' | 'protected' | 'blocked' | 'withheld'; reason: string };

// Our own brands: refused anywhere inside a name.
const BRANDS = ['kaspaveil', 'kaspachat', 'kaspaguy', 'kasveil', 'kastalk'];
// Impersonation words: refused as a whole hyphen-separated part, or at the start or end of a name
// ("binancesupport", "adminbob"), but not inside another word ("badminton").
const OFFICIAL_WORDS = ['official', 'support', 'admin', 'verified', 'security'];
// Ordinary words that start or end with an official word.
const ALLOW = new Set(['supporter', 'supporters', 'supportive', 'administration', 'securityguard']);

// privatePath: the doorman's own list of held names, one per line, kept off the public repo
// (KASPAVEIL_PRIVATE_NAMES). Each is protected outright and as a whole hyphen-separated part ("name-21").
export function loadReserved(csvPath: string, privatePath = process.env.KASPAVEIL_PRIVATE_NAMES): Map<string, { category: string; disposition: 'auction' | 'protected' | 'blocked' }> {
  const m = new Map();
  for (const line of readFileSync(csvPath, 'utf8').trim().split(/\r?\n/).slice(1)) {
    const [name, category, disposition] = line.split(',');
    m.set(name, { category, disposition });
  }
  if (privatePath && existsSync(privatePath)) {
    for (const n of readFileSync(privatePath, 'utf8').split(/\r?\n/).map((l) => l.trim().toLowerCase()).filter(Boolean)) {
      m.set(n, { category: 'private', disposition: 'protected' });
    }
  }
  return m;
}

// Cryptocurrency pattern data generated by registry/reserved/build_reserved.py (patterns.json).
export type Patterns = {
  substrings: string[]; prefixes: string[]; tickers: string[]; suffixes: string[]; allow: string[];
  extensions: Record<string, string[]>; // English words that merely start with a coin name ("asterisk" / aster)
};
export const loadPatterns = (jsonPath: string): Patterns => JSON.parse(readFileSync(jsonPath, 'utf8'));

function cryptoRule(name: string, p: Patterns): string | null {
  const compact = name.replaceAll('-', '');
  if (p.allow.includes(compact)) return null;
  for (const s of p.substrings) if (compact.includes(s)) return `contains ${s}`;
  for (const pre of p.prefixes) {
    if (compact.startsWith(pre) && !(p.extensions[pre] ?? []).some((w) => compact.startsWith(w))) return `starts with the cryptocurrency name ${pre}`;
  }
  for (const t of p.tickers) if (compact.startsWith(t) && p.suffixes.includes(compact.slice(t.length))) return `ticker ${t} + service word`;
  return null;
}

export function checkName(name: string, reserved: ReturnType<typeof loadReserved>, patterns?: Patterns): Verdict {
  // 3-20 characters, as the registry contract requires (MIN_NAME, MAX_NAME)
  if (!/^[a-z0-9](?:[a-z0-9-]{1,18}[a-z0-9])$/.test(name)) return { allowed: false, disposition: 'blocked', reason: 'charset or length' };
  const hit = reserved.get(name);
  if (hit) return { allowed: false, disposition: hit.disposition, reason: hit.category === 'private' ? 'reserved' : `reserved: ${hit.category}` };
  if (name.length <= 3) return { allowed: false, disposition: 'auction', reason: 'short name (3 characters)' };
  if (/^[0-9]{1,4}$/.test(name)) return { allowed: false, disposition: 'auction', reason: 'number up to 4 digits' };
  for (const b of BRANDS) if (name.includes(b)) return { allowed: false, disposition: 'protected', reason: `contains ${b}` };
  const crypto = patterns && cryptoRule(name, patterns);
  if (crypto) return { allowed: false, disposition: 'protected', reason: crypto };
  const parts = name.split('-');
  for (const w of OFFICIAL_WORDS) {
    const edge = (p: string) => !ALLOW.has(p) && (p.startsWith(w) || p.endsWith(w));
    if (parts.some((p) => p === w || edge(p))) return { allowed: false, disposition: 'protected', reason: `impersonation word: ${w}` };
  }
  for (const p of parts) {
    const hit = reserved.get(p);
    if (hit?.disposition === 'blocked') return { allowed: false, disposition: 'blocked', reason: 'offensive part' };
    if (hit?.category === 'private') return { allowed: false, disposition: 'protected', reason: 'reserved' };
  }
  return { allowed: true };
}

// Plus names at launch (Kaspaguy, 2026-10-10): letters, a hyphen, then 2-4 digits, at most 10 characters ("bob-123").
// Plain names are withheld for a later launch; the contract still allows any 1-20 character name, so this is
// policy only and can open up without a contract change. Every other rule of checkName still applies.
export const PLUS_LAUNCH_SHAPE = /^[a-z]{1,7}-[0-9]{2,4}$/;
export const PLUS_LAUNCH_MAX = 10;

export function checkPlusName(name: string, reserved: ReturnType<typeof loadReserved>, patterns?: Patterns): Verdict {
  if (name.length > PLUS_LAUNCH_MAX || !PLUS_LAUNCH_SHAPE.test(name)) {
    return { allowed: false, disposition: 'withheld', reason: 'Plus names are letters-digits (2-4 digits, at most 10 characters) for now' };
  }
  return checkName(name, reserved, patterns);
}

// Held back until the jurisdiction is settled (Kaspaguy, 2026-10-11). The code stays; the doorman doesn't activate it.
// Plus is sold with a chosen launch-shape name (Kaspaguy, 2026-10-11); the name market is held: no auctions (later through
// a VARA-licensed broker-dealer), no single names, no transfers or sales.
// Single names: anything outside the launch shape (plain "bob", "catch22", reserved names won at auction).
// Transfers: handing a name to another key, and resale. The covenant lets an owner transfer or sell without the
// doorman, so for transfers this gate binds Kaspaguy's own services (official app, relay, auctions) only.
export const ACTIVE = { auctions: false, singleNames: false, transfers: false };
export type DoormanAction = 'register' | 'claim-released' | 'auction' | 'transfer' | 'sell';

export function doorman(action: DoormanAction, name: string, reserved: ReturnType<typeof loadReserved>, patterns?: Patterns, active = ACTIVE): Verdict {
  if ((action === 'transfer' || action === 'sell') && !active.transfers) {
    return { allowed: false, disposition: 'withheld', reason: 'name transfers and sales are not active yet' };
  }
  if (action === 'auction' && !active.auctions) return { allowed: false, disposition: 'withheld', reason: 'name auctions are not active yet' };
  return active.singleNames ? checkName(name, reserved, patterns) : checkPlusName(name, reserved, patterns);
}
